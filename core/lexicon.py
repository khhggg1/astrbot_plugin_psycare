@dataclass(frozen=True)
class Term:
    """一条编译好的词条。"""

    pattern: re.Pattern[str]
    weight: int
    dim: str
    crisis: bool


# 只有明确指向自伤/自杀的表达才算「危机」，单独标记后可以立即提醒。
# 「撑不下去」「没有未来」这类高信号词仍计入分数，但交给聚合分数和 LLM 判断，
# 避免一句「作业撑不下去」就触发高危提醒。
_CRISIS_TEXTS = {
    "想死",
    "不想活",
    "活不下去",
    r"活着(?:没|没有|毫无)(?:意思|意义)",
    "自杀",
    "轻生",
    "自残",
    "自伤",
    "割腕",
    "跳楼",
    "跳河",
    "烧炭",
    r"结束(?:自己)?(?:的)?生命",
    r"想结束(?:这)?一切",
    "遗书",
    r"吃(?:了)?(?:很多|一堆|一把)?安眠药",
    "一了百了",
    "死了算了",
    r"不想醒(?:来)?",
    "消失算了",
    "永别",
    r"kill\s*myself",
    "suicide",
    r"self[-\s]?harm",
}


def _compile(raw: dict[str, list[tuple[str, int]]]) -> list[Term]:
    terms: list[Term] = []
    for dim, items in raw.items():
        for text, weight in items:
            terms.append(
                Term(
                    pattern=re.compile(text, re.IGNORECASE),
                    weight=weight,
                    dim=dim,
                    crisis=text in _CRISIS_TEXTS,
                )
            )
    return terms


TERMS: list[Term] = _compile(_TERMS)
_PROTECTIVE_COMPILED = [(re.compile(p), w) for p, w in _PROTECTIVE]

# 供 UI / 文档展示的规模统计
TERM_COUNT = len(TERMS)


def match_terms(text: str, *, respect_negation: bool = True) -> list[Term]:
    """返回文本中命中的词条（同一条消息内同一词条只计一次）。"""
    if not text:
        return []
    hits: list[Term] = []
    for term in TERMS:
        for match in term.pattern.finditer(text):
            if respect_negation and term.weight < 5 and _negated(text, match.start()):
                continue
            # 危机词被否定时直接忽略（「我不会自杀」）
            if respect_negation and term.crisis and _negated(text, match.start()):
                continue
            hits.append(term)
            break
    return hits


def _negated(text: str, start: int) -> bool:
    window = text[max(0, start - 4):start]
    if not window:
        return False
    # 「是不是…」是反问式的自我怀疑，不是否定
    if window.endswith("是不是"):
        return False
    return bool(_NEGATION.search(window))


def protective_score(text: str) -> int:
    """保护性表达的分值（0-3）。"""
    if not text:
        return 0
    total = 0
    for pattern, weight in _PROTECTIVE_COMPILED:
        if pattern.search(text):
            total += weight
    return min(3, total)
